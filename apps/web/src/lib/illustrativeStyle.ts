/**
 * ภาษาภาพของชั้นข้อมูล "ภาพประกอบ" (illustrative) — แหล่งเดียวของค่าสี/ลายเส้น
 *
 * ชั้นที่เราคำนวณเอง (พื้นที่ลุ่มต่ำ จาก DEM) ต้องดูไม่เหมือนชั้นที่ "ตรวจวัดจริง"
 * (น้ำท่วมจากภาพดาวเทียม GISTDA) แม้ในภาพขาวดำ: ของที่ตรวจวัดจริงเป็นพื้นทึบ
 * ส่วนของที่คำนวณเองเป็น "ลายเส้นทแยง" สีม่วง ซึ่งไม่ใช่สีของน้ำ — เห็นแล้วรู้ทันที
 * ว่าไม่ใช่ผิวน้ำที่ใครวัดมา
 *
 * ทั้ง shader (`scene/terrainMaterial.ts`) และสัญลักษณ์ใน legend
 * (`components/layout/MapLegend.tsx`) อ่านค่าจากไฟล์นี้ไฟล์เดียว ห้าม hard-code
 * ซ้ำอีกฝั่ง ไม่งั้นสัญลักษณ์กับสิ่งที่วาดจริงจะเพี้ยนจากกันเงียบ ๆ
 *
 * (E10.4 จะใช้ภาษาภาพชุดเดียวกันนี้กับชั้น flood-exposure)
 */

/** สีลายเส้นแบบ linear RGB 0–1 (ค่าเดียวกับที่ส่งเข้า GLSL) */
export const ILLUSTRATIVE_RGB = {
  /** สีเส้นด้านเข้ม */
  dark: [0.42, 0.28, 0.72] as const,
  /** สีเส้นด้านสว่าง */
  light: [0.7, 0.58, 0.95] as const,
  /**
   * สีเส้นขอบแปลง — เข้มกว่าพื้นที่ระบายไว้ ตรงข้ามกับขอบสีขาวจาง ๆ ของน้ำท่วม
   * GISTDA จึงแยกกันได้แม้ในภาพขาวดำ และแม้แปลงจะเล็กจนไม่มีที่ให้ลายเส้นสลับ
   */
  rim: [0.16, 0.08, 0.34] as const,
};

/**
 * ระยะห่างของลายเส้น หน่วยเป็น "พิกเซลบนจอ" (CSS px) ไม่ใช่พิกัดของภูมิประเทศ
 *
 * ลายนี้จงใจวางในปริภูมิจอภาพ: แปลงลุ่มต่ำส่วนใหญ่กว้างเพียงไม่กี่พิกเซล
 * (วัดที่เพชรบูรณ์ มัธยฐาน 5 px) ถ้าผูกความถี่กับ UV ของจังหวัด ระยะบนจอจะ
 * เปลี่ยนไปตามจังหวัดและตามระยะกล้อง แปลงเล็ก ๆ จึงตกอยู่ในเส้นเดียวและกลาย
 * เป็นพื้นทึบ — ซึ่งคือภาษาที่เราสงวนไว้ให้ข้อมูล "ตรวจวัดจริง"
 */
export const ILLUSTRATIVE_HATCH_PERIOD_PX = 6;

/** สัดส่วนความกว้างของเส้นต่อระยะห่างหนึ่งช่วง (0.5 = เส้นหนาเท่าช่องว่าง) */
export const ILLUSTRATIVE_HATCH_DUTY = 0.5;

/** มุมของลายเส้น (องศา) — 45° เพราะ shader ใช้ (gl_FragCoord.x + gl_FragCoord.y) */
export const ILLUSTRATIVE_HATCH_ANGLE_DEG = 45;

/** น้ำหนักการผสมสีพื้นหลัง (นอกเส้น) เทียบกับบนเส้น — ให้ยังเห็นขอบเขตพื้นที่ */
export const ILLUSTRATIVE_BASE_MIX = 0.22;
export const ILLUSTRATIVE_STRIPE_MIX = 0.44;

/** น้ำหนักของเส้นขอบแปลง */
export const ILLUSTRATIVE_RIM_MIX = 0.5;

/** ความหนาเส้นขอบใน legend (CSS px) ให้พอ ๆ กับที่ shader วาดบนแผนที่ */
export const ILLUSTRATIVE_RIM_WIDTH_PX = 1;

const to255 = (v: number) => Math.round(v * 255);

/** แปลงค่าสี 0–1 เป็น CSS `rgb()` เพื่อให้ SVG ใน legend ใช้ค่าชุดเดียวกับ shader */
export function illustrativeCss(which: keyof typeof ILLUSTRATIVE_RGB): string {
  const c = ILLUSTRATIVE_RGB[which];
  return `rgb(${to255(c[0])}, ${to255(c[1])}, ${to255(c[2])})`;
}
